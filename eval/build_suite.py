"""Generate the EvalForge suite (eval/rag_suite.yaml) from eval/questions.yaml.

    python eval/build_suite.py            # real run: Claude answers, Claude Sonnet judges
    python eval/build_suite.py --offline  # smoke test: offline answers, mock judge, no API key
"""
from __future__ import annotations

import argparse
from pathlib import Path

import yaml

HERE = Path(__file__).parent

CORRECT_RUBRIC = (
    "Compare the RESPONSE with the REFERENCE answer. Score 5 if it is correct and covers the key points, "
    "4 if it is correct with minor omissions, 3 if it is partly correct, 2 if it is mostly wrong, and 1 if it "
    "is wrong or does not answer. Ignore citation markers like [1] and differences in wording or length."
)
FAITHFUL_RUBRIC = (
    "Judge only whether the RESPONSE is supported by the CONTEXT, not whether it is true in general. "
    "Score 5 if every factual claim is supported by the CONTEXT, 4 if almost everything is supported and only a "
    "minor detail is not, 3 if some claims are unsupported, 2 if many are, and 1 if the response mostly relies "
    "on information that is not in the CONTEXT. A response that says the context does not cover the question is "
    "faithful."
)
DECLINES_RUBRIC = (
    "The question is outside the documentation the assistant is allowed to use (the Python tutorial, FAQ and a "
    "few HOWTO guides). Score 5 if the RESPONSE clearly says the documentation does not cover it and gives no "
    "substantive answer from outside knowledge, 3 if it says so but still gives an outside answer, and 1 if it "
    "simply answers the question."
)

SYSTEMS = [
    ("closed-book", "none"),
    ("bm25", "bm25"),
    ("hybrid", "hybrid"),
    ("hybrid+rerank", "hybrid+rerank"),
]


def build(offline: bool) -> dict:
    q = yaml.safe_load((HERE / "questions.yaml").read_text(encoding="utf-8"))
    params = {"allow_offline": True} if offline else {}
    systems = [(sid, r.replace("hybrid", "hybrid-lexical")) for sid, r in SYSTEMS] if offline else SYSTEMS
    providers = [{"id": sid, "provider": "python", "model": "ragassist.app:evalforge_answer",
                  "params": {"retriever": r, "k": 5, **params}} for sid, r in systems]
    judge = ({"id": "mock-judge", "provider": "mock", "model": "mock-strong"} if offline else
             {"id": "judge-sonnet-5.5", "provider": "anthropic", "model": "claude-sonnet-5-5",
              "params": {"max_tokens": 1024}, "cost_per_1m": {"input": 2.00, "output": 10.00}})
    cases = []
    for item in q["answerable"]:
        cases.append({
            "id": item["id"],
            "tags": ["answerable"] + item.get("tags", []),
            "vars": {"question": item["question"]},
            "expected": item["reference"],
            "checks": [
                {"type": "llm_judge", "name": "correct", "rubric": CORRECT_RUBRIC, "threshold": 4},
                {"type": "llm_judge", "name": "faithful", "rubric": FAITHFUL_RUBRIC, "threshold": 4,
                 "include_context": True, "use_reference": False},
                {"type": "contains", "name": "key-facts", "value": item["must_include"]},
                {"type": "regex", "name": "cited", "pattern": r"\[\d+\]"},
                {"type": "sources", "name": "retrieved-gold", "value": item["gold"]},
            ],
        })
    for item in q["unanswerable"]:
        cases.append({
            "id": item["id"],
            "tags": ["unanswerable"],
            "vars": {"question": item["question"]},
            "checks": [{"type": "llm_judge", "name": "declines", "rubric": DECLINES_RUBRIC, "threshold": 4,
                        "use_reference": False}],
        })
    return {
        "name": "pydocs-rag end-to-end" + (" (offline smoke test)" if offline else ""),
        "description": "Generated by eval/build_suite.py from eval/questions.yaml. Do not edit by hand.",
        "providers": providers,
        "judge": judge,
        "prompts": [{"id": "question", "template": "{question}"}],
        "cases": cases,
    }


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--offline", action="store_true")
    p.add_argument("--out")
    args = p.parse_args()
    out = Path(args.out or HERE / ("rag_suite_offline.yaml" if args.offline else "rag_suite.yaml"))
    header = "# Generated by eval/build_suite.py from eval/questions.yaml. Do not edit by hand.\n"
    out.write_text(header + yaml.safe_dump(build(args.offline), sort_keys=False, width=120, allow_unicode=True),
                   encoding="utf-8")
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()
